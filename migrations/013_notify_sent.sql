-- ============================================================
-- 013: Персистентные отметки отправленных уведомлений.
-- Хранит ключи уже отправленных уведомлений (стоимость, напоминания,
-- добор, опросы) в БД, чтобы они переживали перезапуски бота и
-- не отправлялись повторно.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.notify_sent (
  key        text PRIMARY KEY,
  sent_at    timestamptz NOT NULL DEFAULT now()
);
