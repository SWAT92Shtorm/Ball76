-- ============================================================
-- Ball76 — миграция 009: отмена игры.
--
-- Добавляет в таблицу games поле cancelled — признак того, что
-- игра на дату отменена. При отмене все записавшиеся удаляются,
-- в графике игр показывается красный маркер «отм.», а ближайшая
-- игра перестаёт определяться на этот день.
--
-- Применение (на сервере):
--   docker exec -i ball76-db psql -U Ball76 -d Ball76 < migrations/009_game_cancelled.sql
--
-- Миграция идемпотентна (IF NOT EXISTS) — повторный запуск безопасен.
-- ============================================================

ALTER TABLE public.games
  ADD COLUMN IF NOT EXISTS cancelled boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.games.cancelled IS 'Игра отменена (true) — запись закрыта, ближайшая игра не определяется';
